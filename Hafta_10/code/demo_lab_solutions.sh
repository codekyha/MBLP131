#!/bin/bash
# demo_lab_solutions.sh -- Week 10 Lab Sheet: model solutions (Exercises 1-17).
# The exercises build on each other: run them IN ORDER, starting from a FRESH lab:
#     bash ~/mcmp117_lab_setup.sh && cd ~/lab && bash /path/to/demo_lab_solutions.sh
p()   { echo "$USER@$(hostname -s):${PWD/#"$HOME"/"~"}\$ $*"; }   # print the prompt and the command
run() { p "$@"; eval "$@" 2>&1; }                               # ... then run it
ex()  { echo "### Exercise $1"; }

ex 1;  run 'mkdir -p practice/a/b/c'
       run 'tree practice'
ex 2;  run 'touch practice/{one,two,three}.txt'
       run 'ls practice'
ex 3;  run 'cp docs/syllabus.txt backup/syllabus_backup.txt'
       run 'ls -l backup'
ex 4;  run 'ls -i backup/syllabus_backup.txt'
       run 'mv backup/syllabus_backup.txt backup/syllabus_v1.txt'
       run 'ls -i backup/syllabus_v1.txt'
ex 5;  run 'head -n 4 docs/syllabus.txt'
       run 'tail -n 2 docs/syllabus.txt'
ex 6;  run 'wc docs/linux_quotes.txt'
       run 'wc -l data/students.csv'
ex 7;  run 'cat "docs/final report.txt"'
       run 'cat docs/final\ report.txt'
ex 8;  run 'ls photos/img00?.jpg'
       run 'ls photos/img01[0-2].jpg'
       run 'echo photos/*.png'
ex 9;  run 'cd photos'
       run 'mkdir jpg png other'
       run 'mv *.jpg jpg/'
       run 'mv *.png png/'
       run 'mv *.JPG *.jpeg other/'
       run 'tree'
       run 'cd ..'
ex 10; run 'echo docs/*'
       run 'ls -a docs'
ex 11; run 'cp -r docs backup/docs_copy'
       run 'ls -A backup/docs_copy'
       run 'du -sh docs backup/docs_copy'
ex 12; run 'file README.txt src/hello.c photos/jpg/img001.jpg logs'
       run 'du -sh data logs photos src'
ex 13; run 'touch -d "2026-09-01 12:00" docs/notes_01.txt'
       run 'stat -c "%n | access %x | modify %y" docs/notes_01.txt'
       run 'ls -l docs/notes_01.txt'
ex 14; run 'ln docs/syllabus.txt docs/syllabus_hard.txt'
       run 'ls -li docs/syllabus.txt docs/syllabus_hard.txt'
       run 'rm docs/syllabus.txt'
       run 'ls -li docs/syllabus_hard.txt'
       run 'head -n 2 docs/syllabus_hard.txt'
ex 15; run 'ln -s projects/alpha/docs alpha_docs'
       run 'ls alpha_docs/'
       run 'mv projects/alpha projects/alpha_old'
       run 'ls alpha_docs/'
       run 'rm alpha_docs'
       run 'ln -s projects/alpha_old/docs alpha_docs'
       run 'ls -l alpha_docs'
ex 16; run 'mkdir -p course/week{01..14}/{slides,notes}'
       run 'ls course'
       run 'ls course/week10'
ex 17; run 'rmdir practice'
       run 'rm -r practice course'
       run 'ls'
